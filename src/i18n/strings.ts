export const dictionaries = { en, fr, ar } as const;
export type UiLanguage = keyof typeof dictionaries;

/** Speech language code used for each interface language. */
export const speechLang: Record<UiLanguage, string> = { en: 'en', fr: 'fr', ar: 'ar' };

export const SIGN_LANGUAGES = ['asl', 'lsf', 'lsm', 'arsl', 'bsl', 'custom'] as const;
export type SignLanguage = (typeof SIGN_LANGUAGES)[number];

/** Returns a translator function for one language: t('key', { n: 3 }). */
export function translator(lang: UiLanguage) {
  const dict = dictionaries[lang];
  return (key: StringKey, vars?: Record<string, string | number>): string => {
    let text = dict[key];
    if (vars) for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, String(v));
    return text;
  };
}
export type Translate = ReturnType<typeof translator>;
